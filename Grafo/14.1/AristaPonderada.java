public class AristaPonderada {
    public int srcVert;     // vértice de origen
    public int destVert;    // vértice de destino
    public int distance;    // peso de la arista

    // Constructor
    public AristaPonderada(int sv, int dv, int d) {
        srcVert = sv;
        destVert = dv;
        distance = d;
    }
}